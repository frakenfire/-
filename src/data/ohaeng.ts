// 다섯 갈래마다 정해진 것들 — 방위, 숫자, 시각, 맛, 빛깔.
//
// 왜 이 표가 필요한가: 행운 여섯 칸(색·숫자·방향·시간·음식·물건) 중 다섯이
// 날짜 해시로 목록에서 뽑는 제비였다. 방향은 후보 일곱 중 하나, 시간은 여섯 중
// 하나, 숫자는 1~45 난수. 앱은 홈에서 "인공지능이 그때그때 지어내지 않아요.
// 그 규칙으로 점수를 매겨요" 라고 약속해놓고, 이 카드만 정반대였다.
//
// 그런데 이 다섯은 지어낼 필요가 없다. 예부터 기운마다 방위와 수와 시각과 맛이
// 정해져 있다. 오늘 나한테 힘이 되는 기운 하나만 정해지면 나머지는 전부 계산이다.
//
//   기운   방위   숫자    가장 센 시각        맛
//   나무   동     3·8     이른 아침(3~7시)    신맛
//   불     남     2·7     점심 무렵(9~13시)   쓴맛
//   흙     가운데 5·10    이른 오후(13~15시)  단맛
//   쇠     서     4·9     늦은 오후(15~19시)  매운맛
//   물     북     1·6     밤(21~1시)          짠맛
//
// 숫자는 하도(河圖)의 수다. 이 표는 관법 논쟁이 없는 고정값이라 여기 그대로 적는다.
// 어떤 기운을 '나한테 힘이 되는' 것으로 볼지는 별개 문제이고, 그건 saju.ts 가 정한다.
//
// 말은 초등학생이 읽어도 걸리지 않게 쓴다. 한자도, 어려운 말도 넣지 않는다.

export type OhaengFacts = {
  /** 나무 / 불 / 흙 / 쇠 / 물 */
  ko: string;
  /** 동쪽 / 남쪽 / 가운데 / 서쪽 / 북쪽 */
  direction: string;
  /** 왜 그 방향인지. 뒷말에 이어붙는 '~니까' 꼴로 적는다 */
  directionWhy: string;
  /** 이 기운에 붙는 두 숫자 */
  numbers: [number, number];
  /** 이 기운이 하루 중 가장 센 때 */
  time: string;
  /**
   * 그 때가 끝나는 시각(24시간). luckyWhen 이 '이미 지나갔나' 를 이걸로 잰다.
   *
   * 전에는 luckyWhen 이 제 안에 여섯 구간의 끝 시각을 따로 들고 있었다. 그런데
   * 화면에 실제로 뜨는 시각은 여기 time 이라, 두 표가 어긋나 있었다. '이른 오후'
   * 는 luckyWhen 쪽 표에 아예 없어서 밤 열한 시에도 '이른 오후' 라고 떴다.
   * 흙이 용신인 사람은 몇 시에 열든 늘 오후라고 들었다. 끝 시각을 시각을 적는
   * 자리 바로 옆에 둬서 다시는 갈라지지 않게 한다.
   */
  timeEnd: number;
  /** 왜 그 시각인지. 뒷말에 이어붙는 '~니까' 꼴로 적는다 */
  timeWhy: string;
  /** 이 기운의 맛 */
  taste: string;
  /** 그 맛에 드는 먹을거리 */
  foods: string[];
  /** 이 기운에 드는, 손에 쥘 수 있는 것 */
  items: string[];
  /** 빛깔을 한마디로 */
  colorWhy: string;
  /** 이 요소에 드는 빛깔 이름. 피할 요소로 쓰일 때 '오늘 멀리하면 좋은 빛깔' 이 된다 */
  colors: string[];
  /** 이 요소에 어울리는 음악 */
  music: string[];
};

