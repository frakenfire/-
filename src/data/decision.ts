// 결정 카드 - 이 리포트가 실패하지 않으려면 여기서 끝이 나야 한다.
//
// 사용자가 다 읽고 "그래서 지금 뭘 하라는 거지" 가 남으면 진 것이다. 그래서
// 이 표는 해석을 하지 않는다. 지금 어느 상태인지 한 단어로 박고, 오늘 손에
// 잡히는 행동 세 개와 하지 말 행동 세 개를 준다.
//
// 상태는 이번 달 판정과 가장 좋은 달까지의 거리에서 나온다.
//   run   지금 실행하기      이번 달이 열려 있고 총점도 받쳐줄 때
//   prep  지금 준비하기      곧 열리는데 아직은 아닐 때
//   hold  지금 결정하지 않기 이번 달이 버거울 때
//   keep  지금 유지하기      어느 쪽으로도 안 기울 때

export type Stance = 'run' | 'prep' | 'hold' | 'keep';

// '지금 유지하기' 는 '아무것도 하지 마' 로 읽혔다. 뜻은 그게 아니라
// '새로 벌이지 말고 하던 것을 이어가라' 다. 바로 아래 줄이 '연봉이나 맡는
// 범위를 올리는 쪽' 이라고 말하는데 칩은 유지하라고 하니 서로 반대로 들렸다.
export const STANCE_WORD: Record<Stance, string> = {
  run: '지금 실행하기',
  prep: '지금 준비하기',
  hold: '지금 결정하지 않기',
  keep: '하던 대로 이어가기',
};

