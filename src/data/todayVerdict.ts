/** 고민과 고른 상황으로 오늘 전체 종합을 고른다. 상황을 안 골랐으면 기본값. */
export function todayAskOf(concern: ConcernKey, optionKey: string | null, band: Band, pick = 0): Verdict & { band: Band } {
  const byOption = TABLE[concern];
  const key = optionKey && byOption[optionKey] ? optionKey : FALLBACK[concern];
  const cell = byOption[key].a[band];
  const list = Array.isArray(cell) ? cell : [cell];
  return { ...list[Math.abs(pick) % list.length], band };
}

