// 이 앱은 매일 쪽지를 뽑는 앱이다. 그런데 화면은 올해와 십 년 얘기로 가득 차
// 있고, 정작 '오늘 어떻게 하라는 건데' 에 답하는 자리가 없었다.
//
// 그다음에는 '결과가 둥글게 말해서 무슨 말인지 모르겠다' 는 말을 들었다.
// 결론이 한쪽만 말했다. '오늘은 이직 얘기를 꺼내도 돼요' 만 있으면 어디까지
// 해도 되는지 모르고, '오늘은 지원하지 마세요' 만 있으면 그럼 뭘 하라는
// 건지 모른다. 그래서 head 는 해도 되는 것과 하지 말 것을 한 문장에 같이
// 말한다. sum 은 그렇게 본 까닭이다. 할 일을 또 적지 않는다 - 할 일은
// 바로 아래 '오늘 할 것' 카드가 맡는다.
//
// 고민만 보고 물으면 안 된다. '지금은 쉬는 중이에요' 를 고른 사람에게
// '오늘 이직 얘기를 꺼내도 될까요' 라고 물으면, 꺼낼 자리가 없는 사람에게
// 묻는 말이 된다. 고른 상황까지 본다.
//
// 고민 여섯 x 상황 넷 = 스물넷. 거기에 오늘 점수 밴드 셋을 곱해 일흔둘.
//
// 몸과 돈은 따로 선을 긋는다. 운세가 병원에 갈지, 투자를 할지를 대신 정하면
// 안 된다. 병원 가라·가지 마라, 투자하라·사라는 말은 여기 없다 -
// todayDecision.test 가 본다.

