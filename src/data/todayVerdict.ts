// 2026-10-12 사장님 본보기로 다시 썼다. 비유와 돌려 말하기 대신 읽자마자 무슨
// 행동인지 알게 쓴다.
//   head 첫 문장  오늘 할 핵심 행동 하나. '오늘은 ~해보세요.' 화면의 큰 결론이다.
//   head 둘째 문장  오늘 하지 않는 게 좋은 것. '~하지 마세요.'
//   sum  무엇을 구체적으로 볼지(특히 ~, ~), 그러면 무엇이 좋은지, 필요하면 그
//        상황의 마음 한 문장. 문장은 짧게. head 와 같은 말을 되풀이하지 않는다.
// 연봉, 담당 업무, 마감일, 카드 내역처럼 그 사람의 실제 하루에 있는 물건과 일을 쓴다.
//
// 고민만 보고 물으면 안 된다. '지금은 쉬는 중이에요' 를 고른 사람에게 출근 얘기를
// 하면 꺼낼 자리가 없는 사람에게 하는 말이 된다. 고른 상황까지 본다.
//
// 고민 여섯 x 상황 넷 = 스물넷. 거기에 오늘 점수 밴드 셋을 곱해 일흔둘.
// 칸마다 네 벌을 둬서 이백여든여덟 벌이다. 같은 밴드가 나와도 날짜가 바뀌면
// 다른 행동을 말한다. 네 벌은 밴드 판정(good 은 해도 되는 날, ok 는 조건을 단
// 작은 한 걸음, hard 는 서두르지 않는 날)을 똑같이 지킨다.
//
// 아래 '할 것·하지 말 것' 카드는 다른 표에서 나온다. 둘이 반대로 말하지 않게
// head 에는 연락, 결정, 약속, 운동 같은 낱말을 되도록 쓰지 않는다 -
// todayDecision.test 가 본다.
//
// 몸과 돈은 따로 선을 긋는다. 운세가 병원에 갈지, 투자를 할지를 대신 정하면
// 안 된다. 병원 가라·가지 마라, 투자하라·사라는 말은 여기 없다.

