/** 고민과 고른 상황으로 오늘 묻는 말과 답을 고른다. 상황을 안 골랐으면 기본값. */
export function todayAskOf(concern: ConcernKey, optionKey: string | null, band: Band) {
  const byOption = TABLE[concern];
  const key = optionKey && byOption[optionKey] ? optionKey : FALLBACK[concern];
  const row = byOption[key];
  return { q: row.q, a: row.a[band], band };
}

export { TABLE as TODAY_TABLE };
