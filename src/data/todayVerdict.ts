// 먼저 짚고 넘어간다.
//
// 고민만 보고 물으면 안 된다. '지금은 쉬는 중이에요' 를 고른 사람에게
// '오늘 이직 얘기를 꺼내도 될까요' 라고 물으면, 꺼낼 자리가 없는 사람에게
// 묻는 말이 된다. 고른 상황까지 본다.
//
