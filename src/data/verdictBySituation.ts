//
// 전에는 고민만 보고 골랐다. 그래서 '지금은 쉬는 중이에요' 를 고른 사람에게
// '올해는 이직보다 현재 직장을 유지하는 편이 나아요' 가 나갔다. 지킬 자리가 없는
// 사람에게 자리를 지키라고 한 것이다. 그 밑줄은 한술 더 떴다 -
// '여기서 연봉을 올리거나 맡는 일을 넓혀보세요'. 다닐 곳이 없는 사람이다.
//
// 상황을 물어놓고 답에 안 쓰면 그 화면은 물어본 적이 없는 것과 같다.
// 고민 여섯 x 상황 넷 x 판정 셋 = 일흔둘. 전부 따로 쓴다.
//
// 그다음에는 wait 가 판정을 피했다. '올해는 결론을 서두르지 않아도 돼요',
// '올해는 상대를 재촉하지 않는 해예요' 는 올해 뭘 하라는 건지 없다. wait 는
// '올해는 X 보다 Y 를 하는 해예요' 로 적고 밑줄에 언제까지를 박는다. soon 의
// {when} 은 실제로 잰 거리로 채운다(deepRead 가 '다음 달에' 나 '2달 뒤에' 로 바꿔
// 넣는다). 그래서 soon 의 head 는 '{when} 지원서를 넣어보세요' 처럼 그 달에 할
// 행동으로 끝낸다.
//
// 시키는 말(~하세요, ~하지 마세요)은 권하는 말(~해보세요, ~해두면 좋아요,
// ~보다 ~가 나아요)로 바꿨다. 판정과 시점, 숫자는 그대로다.

