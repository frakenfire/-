/** 상황을 안 골랐을 때 쓸 기본 상황 */
const DEFAULT_SITUATION: Record<ConcernKey, string> = {
  work: 'stay', money: 'save', love: 'alone', people: 'work', health: 'tired', mind: 'anxious',
};

export function verdictTwoOf(concern: ConcernKey, optionKey: string | null, verdict: Verdict): Two {
  const byOption = VERDICT_BY_SITUATION[concern];
  const key = optionKey && byOption[optionKey] ? optionKey : DEFAULT_SITUATION[concern];
  return byOption[key][verdict];
}
