// 타고난 구조 — '오늘 어떠냐' 가 아니라 '나는 원래 어떤 사람이냐'.
//
// 이 자리만 평생 안 바뀐다. 해와 달은 계속 굴러가지만 원국 여덟 글자는 그대로다.
// 그래서 여기 문장만은 날짜와 무관하게 같은 사람에게 늘 같게 나온다.
//
// 원국에서 제일 두꺼운 기운의 무리(다섯 중 하나)로 갈린다.
//   self      나를 세우는 쪽
//   output    꺼내 보이는 쪽
//   wealth    거두는 쪽
//   authority 자리와 규칙 쪽
//   support   받쳐주는 쪽
//
// 다섯 칸은 한 화면에 나란히 뜬다. 칸끼리 같은 말을 되풀이하지 않고,
// 칸마다 그 무리라서 생기는 장면(계약서, 통장, 데이트, 끼니)을 하나씩 넣는다.
// trap 도 명사로 끊지 않고 '~해요' 문장으로 단정해서 쓴다. '~기 쉬워요' 를
// 줄마다 붙이면 전부 추측처럼 읽혀서 한 칸에 한 번까지만 둔다.

export type ShapeRow = {
  /** 들어오는 방식 */
  inflow: string;
  /** 커지는 방식 */
  grow: string;
  /** 인정으로 이어지는 방식 — 커지는 것과 올라가는 것은 다른 이야기다 */
  rise: string;
  /** 새는 방식 */
  leak: string;
  /** 반복하기 쉬운 실수 */
  trap: string;
};

