
// 오늘 할 것과 하지 말아야 할 것 - 오늘 일진의 십성을 고른 주제에 대어 뽑는다.
//
// 이 표가 생기기 전에는 '오늘은 이렇게' 가 일진 풀이에서 그대로 왔다. 그래서
// 일과 이직을 고른 사람에게 '입만 즐겁고 몸은 잊는 것을 피하세요' 가 붙었다.
// 주제를 골라 들어온 사람에게 생활 습관 조언을 주면 그 화면은 거기서 끝난다.
//
// 한동안 이 표에는 행동만 있고 까닭이 없었다. '하면 좋은 것: 서류 요건을
// 맞춰보기' 를 읽은 사람은 왜 하필 오늘 그걸 해야 하는지 몰랐다. 그래서
// 칸마다 까닭을 붙였다. 까닭은 그 행동에만 맞는 말이어야 한다. 할 것과 하지
// 말 것에 같은 까닭을 돌려 쓰면 둘 다 안 읽힌다 - todayDecision.test 가 본다.
//
// doIt      오늘 할 것. '~하세요' 로 끝난다
// doWhy     왜 오늘 그걸 하면 좋은가
// avoid     오늘 하지 말아야 할 것. '~마세요' 로 끝난다
// avoidWhy  하면 무슨 일이 생기는가
//
// 표 자체는 optionDay/ 에 고른 상황마다 따로 있다. 여기는 칸의 모양만 둔다.

export type DayAct = { doIt: string; doWhy: string; avoid: string; avoidWhy: string };
