/** 일간·일지 자리 번호로 일주 이름을 만든다. '갑' + '자' = '갑자' */
export function dayPillarKey(stemIdx: number, branchIdx: number): string {
  return STEMS[stemIdx].kor + BRANCHES[branchIdx].kor;
}

/** 없는 조합(예순 가지 밖)은 null. 있는 척 지어내지 않는다 */
export function dayPillarOf(stemIdx: number, branchIdx: number): DayPillarRead | null {
  return DAY_PILLAR[dayPillarKey(stemIdx, branchIdx)] ?? null;
}
