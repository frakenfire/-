// 일주(日柱) 예순 가지 — '나는 어떤 사람인가' 를 사주에서 제일 먼저 보는 자리.
//
// 여태 이 앱은 일간 열 가지만 읽었다(dayMaster.ts). 그런데 명리에서 사람을
// 가리키는 최소 단위는 일간 하나가 아니라 일간과 일지가 붙은 한 기둥이다.
// 같은 갑목이라도 갑자와 갑신은 다른 사람이다. 앞은 받쳐주는 물 위에 서 있고
// 뒤는 자기를 치는 쇠 위에 서 있다. 열 가지만 읽으면 열 명 중 한 명꼴로
// 같은 말을 받는데, 예순 가지면 예순 명 중 한 명이다.
//
// 쓰는 규칙은 dayMaster.ts 와 같다.
//  - 비유를 걷는다. '바위 위의 소나무' 는 한 번 더 풀어야 뜻이 닿는다.
//    사람을 바로 가리키는 말로 쓴다 — 혼자 서는 사람, 끝까지 버티는 사람.
//  - 좋은 말만 하지 않는다. watch 가 없으면 '나를 봤다' 는 느낌이 안 생긴다.
//  - 단정한다. '~하는 편이에요' 를 줄마다 붙이면 예순 줄이 전부 추측처럼
//    읽힌다. line 과 strong 은 '~해요' 로 끊고, '~기 쉬워요' 는 watch 한 줄에만 둔다.
//  - 오늘 운이 아니라 성질이다. 오늘 이야기는 일진과 만나야 나온다.
//  - 누구에게나 맞는 말을 쓰지 않는다. 그 일지가 일간에게 무엇인지(배움,
//    돈, 규칙, 표현, 같은 편)에서 나오는 장면을 쓴다. 회의, 장보기, 통장처럼.

