/** 상황을 안 골랐을 때 쓸 기본 상황 */
const FALLBACK: Record<ConcernKey, string> = {
  work: 'stay', money: 'save', love: 'alone', people: 'work', health: 'tired', mind: 'anxious',
};

export function planOf(concern: ConcernKey, optionKey: string | null): Plan {
  const byOption = SITUATION_PLAN[concern];
  return byOption[optionKey && byOption[optionKey] ? optionKey : FALLBACK[concern]];
}
