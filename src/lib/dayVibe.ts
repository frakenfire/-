import { hashSeed } from './dateSeed.ts';

// 오늘의 한 줄 — 홈 카드 맨 위. 날짜만으로 정해진다.
//
// 예전에는 '오늘은 [낱말]이 어울리는 날이에요' 라는 틀에 낱말 열 개를 끼웠다.
// 틀에 끼우는 말은 낱말마다 문법이 달라서 대부분 어색했고, 몇 개는 아예
// 틀렸다. '제안이 어울리는 날' 은 번역한 말 같고, '다정이 어울리는 날' 은
// 다정이 명사가 아니라서 문장이 안 된다. '어울리는 날' 자체가 사람이
// 하는 말이 아니다.
//
// 그래서 틀을 걷고 한 문장씩 손으로 썼다. head 는 오늘 뭘 하면 되는지,
// line 은 그러면 무슨 일이 생기는지. line 이 또 '~날이에요' 로 끝나면 두 줄이
// 연달아 같은 말끝이 되므로 line 은 날이라는 말을 안 쓴다.

export type DayVibe = { head: string; line: string };

const VIBES: DayVibe[] = [
  { head: '오늘은 벌이기보다 정리하는 날이에요.', line: '하나씩 치우다 보면 막혔던 게 풀려요.' },
  { head: '오늘은 사람을 만나면 좋아요.', line: '먼저 연락한 쪽에서 반가운 얘기가 나와요.' },
  { head: '오늘은 쉬어 가도 괜찮아요.', line: '무리하지 않은 만큼 내일 힘이 남아요.' },
  { head: '오늘은 먼저 말을 꺼내 보세요.', line: '작은 부탁이나 제안이 쉽게 받아들여져요.' },
  { head: '오늘은 천천히 가도 돼요.', line: '서두르지 않으면 놓쳤던 걸 챙기게 돼요.' },
  { head: '오늘은 한 가지만 붙잡으세요.', line: '여러 개를 벌이면 하나도 안 끝나요.' },
  { head: '오늘은 먼저 다정하게 대해 보세요.', line: '건넨 말 한마디가 그대로 돌아와요.' },
  { head: '오늘은 안 해본 걸 하나 해 보세요.', line: '작게 시작해도 생각보다 잘 풀려요.' },
  { head: '오늘은 하던 대로 하면 돼요.', line: '익숙한 데서 힘이 나와요.' },
  { head: '오늘은 작은 일에 기분이 좋아져요.', line: '평소 지나치던 것을 한 번 들여다보세요.' },
];

export function todayVibe(dateKey: string): DayVibe {
  return VIBES[hashSeed(`vibe|${dateKey}`) % VIBES.length];
}
