// 오늘의 한 줄 — 홈 카드 맨 위. 날짜만으로 정해진다.
//
// 예전에는 '오늘은 [낱말]이 어울리는 날이에요' 라는 틀에 낱말 열 개를 끼웠다.
// 틀에 끼우는 말은 낱말마다 문법이 달라서 대부분 어색했고, 몇 개는 아예
// 틀렸다. '제안이 어울리는 날' 은 번역한 말 같고, '다정이 어울리는 날' 은
// 다정이 명사가 아니라서 문장이 안 된다. '어울리는 날' 자체가 사람이
// 하는 말이 아니다.
//
// 그래서 틀을 걷고 한 문장씩 손으로 썼다. head 는 오늘 뭘 하면 되는지,
// line 은 그러면 무슨 일이 생기는지. line 이 또 '~날이에요' 로 끝나면 두 줄이
// 연달아 같은 말끝이 되므로 line 은 날이라는 말을 안 쓴다.
//
// decision 은 고민을 안 고르고 뽑은 결과의 맨 위 결론이다. 고민을 고른 결과와
// 같은 모양(오늘 전체 종합, 할 것과 까닭, 하지 말 것과 까닭)으로 그린다.
// 홈에서 본 오늘 한 줄과 같은 날의 말이라, 홈과 결과가 서로 다른 날을
// 말하지 않는다.
//
// 사장님 본보기(2026-10-12)대로 쓴다. 전체 종합 첫 문장은 오늘 할 일 하나를
// '오늘은 ~해보세요.' 로 말하고, 설명은 무엇을 보고 적고 말하는지를 짧게 적는다.
// 할 것은 '~해보세요/~하세요.', 하지 말 것은 '~하지 마세요.' 로 끝낸다.
// 까닭 칸 첫 문장은 어떻게, 둘째 문장은 그러면 무엇이 좋은지. 하지 말 것의
// 까닭에는 대신 무엇을 할지를 넣는다. 할 일은 전부 오늘 안에 하는 일이다.

